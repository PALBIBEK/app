/**
 * Style Dictionary build — emits CSS custom properties, TS object, JSON.
 * Light → :root / [data-theme="light"]
 * Dark  → [data-theme="dark"]
 * Density → [data-density="comfortable|compact"]
 */
import StyleDictionary from "style-dictionary";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { mkdirSync, writeFileSync } from "node:fs";

const root = dirname(fileURLToPath(import.meta.url));
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

function flatten(obj, prefix = [], out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    if (v && typeof v === "object" && !Array.isArray(v)) {
      if ("value" in v) {
        out[[...prefix, k].join("-")] = String(v.value);
      } else {
        flatten(v, [...prefix, k], out);
      }
    } else if (typeof v === "string" || typeof v === "number") {
      out[[...prefix, k].join("-")] = String(v);
    }
  }
  return out;
}

async function buildTheme(name, sources) {
  const sd = new StyleDictionary({
    source: sources,
    platforms: {
      intermediate: {
        transformGroup: "css",
        buildPath: join(dist, ".tmp/"),
        files: [
          {
            destination: `${name}.json`,
            format: "json/nested",
          },
        ],
      },
    },
    log: { verbosity: "silent" },
  });
  await sd.hasInitialized;
  await sd.buildAllPlatforms();
  const nested = JSON.parse(
    await import("node:fs").then((fs) =>
      fs.readFileSync(join(dist, ".tmp", `${name}.json`), "utf8"),
    ),
  );
  return flatten(nested);
}

const primitive = join(root, "src/primitive/base.json");
const lightFlat = await buildTheme("light", [
  primitive,
  join(root, "src/semantic/light.json"),
]);
const darkFlat = await buildTheme("dark", [
  primitive,
  join(root, "src/semantic/dark.json"),
]);

function toCssVars(flat, indent = "  ") {
  return Object.entries(flat)
    .map(([k, v]) => `${indent}--${k}: ${v};`)
    .join("\n");
}

const densityComfortable = `  --density-row-height: 44px;\n  --density-padding-y: 12px;\n  --density-gap: 12px;`;
const densityCompact = `  --density-row-height: 32px;\n  --density-padding-y: 6px;\n  --density-gap: 8px;`;

const css = `/* Generated by @yal/tokens — do not edit by hand */
:root,
[data-theme="light"] {
${toCssVars(lightFlat)}
${densityComfortable}
}

[data-theme="dark"] {
${toCssVars(darkFlat)}
}

[data-density="comfortable"] {
${densityComfortable}
}

[data-density="compact"] {
${densityCompact}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --motion-fast: 0ms;
    --motion-base: 0ms;
  }
}
`;

writeFileSync(join(dist, "tokens.css"), css);

const ts = `/* Generated by @yal/tokens — do not edit by hand */
export const tokens = ${JSON.stringify({ light: lightFlat, dark: darkFlat }, null, 2)} as const;
export type TokenName = keyof typeof tokens.light;
`;
writeFileSync(join(dist, "tokens.ts"), ts);
writeFileSync(join(root, "src/generated/tokens.ts"), ts);
writeFileSync(
  join(dist, "tokens.json"),
  JSON.stringify({ light: lightFlat, dark: darkFlat }, null, 2),
);

console.log("Built tokens → dist/tokens.{css,ts,json}");
